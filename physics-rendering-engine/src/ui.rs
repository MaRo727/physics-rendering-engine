/// Pack the 8×8 font into 192 u32s for GPU upload.
/// Layout: glyph `i` occupies `[i*2]` (rows 0-3) and `[i*2+1]` (rows 4-7).
pub fn font_gpu_data() -> [u32; 192] {
    let mut out = [0u32; 192];
    let mut i = 0;
    while i < 96 {
        let g = &FONT_8X8[i];
        out[i * 2] = (g[0] as u32) << 24
            | (g[1] as u32) << 16
            | (g[2] as u32) << 8
            | g[3] as u32;
        out[i * 2 + 1] = (g[4] as u32) << 24
            | (g[5] as u32) << 16
            | (g[6] as u32) << 8
            | g[7] as u32;
        i += 1;
    }
    out
}

// -------------------------------------------------------------------------
// Immediate-mode builder
// -------------------------------------------------------------------------

pub struct Ui {
    prims: Vec<UiPrimitive>,
    screen_w: f32,
    screen_h: f32,
}

impl Ui {
    pub fn new() -> Self {
        Self {
            prims: Vec::with_capacity(1024),
            screen_w: 1.0,
            screen_h: 1.0,
        }
    }

    pub fn begin_frame(&mut self, w: f32, h: f32) {
        self.prims.clear();
        self.screen_w = w;
        self.screen_h = h;
    }

    pub fn screen_size(&self) -> (f32, f32) {
        (self.screen_w, self.screen_h)
    }

    /// Solid coloured rectangle.
    pub fn rect(&mut self, x: f32, y: f32, w: f32, h: f32, color: [f32; 4]) {
        self.prims.push(UiPrimitive {
            rect: [x, y, w, h],
            color,
            glyph: 0,
            flags: 0,
            _pad: [0; 2],
        });
    }

    /// Solid rectangle with a 1 px border.
    pub fn rect_border(&mut self, x: f32, y: f32, w: f32, h: f32, color: [f32; 4]) {
        self.prims.push(UiPrimitive {
            rect: [x, y, w, h],
            color,
            glyph: 0,
            flags: 1,
            _pad: [0; 2],
        });
    }

    /// Draw a string.  `scale` is the integer pixel multiplier (1 = 8 px, 2 = 16 px, …).
    pub fn text(&mut self, x: f32, y: f32, s: &str, scale: f32, color: [f32; 4]) {
        let cell = 8.0 * scale;
        for (i, ch) in s.chars().enumerate() {
            let code = ch as u32;
            if code < 32 || code > 127 {
                continue;
            }
            self.prims.push(UiPrimitive {
                rect: [x + i as f32 * cell, y, cell, cell],
                color,
                glyph: code,
                flags: 0,
                _pad: [0; 2],
            });
        }
    }

    /// HP / mana / stamina style bar with optional label.
    pub fn bar(
        &mut self,
        x: f32,
        y: f32,
        w: f32,
        h: f32,
        fraction: f32,
        fill: [f32; 4],
        bg: [f32; 4],
    ) {
        // Background.
        self.rect_border(x, y, w, h, bg);
        // Filled portion (inset by 1 px for border).
        let inner_w = (w - 2.0) * fraction.clamp(0.0, 1.0);
        if inner_w > 0.0 {
            self.rect(x + 1.0, y + 1.0, inner_w, h - 2.0, fill);
        }
    }

    /// A labelled bar: "LABEL" text then a bar to the right.
    pub fn labelled_bar(
        &mut self,
        x: f32,
        y: f32,
        label: &str,
        bar_w: f32,
        bar_h: f32,
        fraction: f32,
        text_color: [f32; 4],
        fill: [f32; 4],
        bg: [f32; 4],
        scale: f32,
    ) {
        let cell = 8.0 * scale;
        self.text(x, y, label, scale, text_color);
        let bar_x = x + label.len() as f32 * cell + 4.0;
        self.bar(bar_x, y + 1.0, bar_w, bar_h, fraction, fill, bg);
    }

    /// Semi-transparent panel background.
    pub fn panel(&mut self, x: f32, y: f32, w: f32, h: f32) {
        self.rect(x, y, w, h, [0.0, 0.0, 0.0, 0.75]);
    }

    /// Dialogue box — centered at the bottom of the screen.
    /// Shows a speaker name and up to 3 lines of wrapped text.
    pub fn dialogue_box(
        &mut self,
        speaker: &str,
        lines: &[&str],
        scale: f32,
    ) {
        let cell = 8.0 * scale;
        let line_h = cell + 2.0;
        let max_lines = lines.len().min(4);
        let box_w = 40.0 * cell;
        let box_h = (max_lines as f32 + 2.0) * line_h + 12.0;
        let bx = (self.screen_w - box_w) * 0.5;
        let by = self.screen_h - box_h - 24.0;

        // Background panel.
        self.rect(bx, by, box_w, box_h, [0.05, 0.05, 0.1, 0.85]);
        // Top border accent.
        self.rect(bx, by, box_w, 2.0, [0.4, 0.4, 0.6, 0.9]);

        // Speaker name.
        self.text(bx + 8.0, by + 6.0, speaker, scale, [0.9, 0.8, 0.3, 1.0]);
        // Separator.
        let sep_y = by + line_h + 6.0;
        self.rect(bx + 4.0, sep_y, box_w - 8.0, 1.0, [0.3, 0.3, 0.4, 0.8]);

        // Text lines.
        let text_color = [0.85, 0.85, 0.85, 1.0];
        for (i, &line) in lines.iter().take(4).enumerate() {
            self.text(
                bx + 8.0,
                sep_y + 4.0 + i as f32 * line_h,
                line,
                scale,
                text_color,
            );
        }
    }

    pub fn primitives(&self) -> &[UiPrimitive] {
        &self.prims
    }
}

// -------------------------------------------------------------------------
// GPU buffer helpers  (sizes / offsets for SSBO layout)
