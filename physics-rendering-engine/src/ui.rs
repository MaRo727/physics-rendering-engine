/// Immediate-mode UI system.
///
/// Each frame the engine calls `begin_frame`, emits text/rects/bars, then
/// `primitives()` returns a flat slice ready for GPU upload.  The raygen
/// shader reads the UI SSBO and composites the primitives over the scene.

// -------------------------------------------------------------------------
// GPU-matched types
// -------------------------------------------------------------------------

/// Matches the `UiPrim` struct in the raygen shader (std430, 48 bytes).
#[repr(C)]
#[derive(Clone, Copy)]
pub struct UiPrimitive {
    pub rect: [f32; 4],  // x, y, w, h  (screen pixels)
    pub color: [f32; 4], // r, g, b, a
    pub glyph: u32,      // 0 = solid rect, 32..127 = ASCII glyph
    pub flags: u32,      // bit 0 = 1px border
    pub _pad: [u32; 2],
}

/// Header at the start of the UI SSBO, followed by font data and primitives.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct UiHeader {
    pub count: u32,
    pub screen_w: u32,
    pub screen_h: u32,
    pub _pad: u32,
}

