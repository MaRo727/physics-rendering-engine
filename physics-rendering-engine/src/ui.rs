/// Total byte size of header + font block (constant per frame).
pub const UI_FIXED_BYTES: usize =
    std::mem::size_of::<UiHeader>() + 192 * std::mem::size_of::<u32>();

/// Maximum primitives we support.
pub const MAX_UI_PRIMS: usize = 4096;

/// Total SSBO byte capacity.
pub const UI_BUFFER_BYTES: usize =
    UI_FIXED_BYTES + MAX_UI_PRIMS * std::mem::size_of::<UiPrimitive>();
